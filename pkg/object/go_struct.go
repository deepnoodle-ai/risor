// structMeta caches reflection metadata for a struct type.
type structMeta struct {
	fields  map[string]int // field name -> field index
	methods map[string]int // method name -> method index (on pointer type)
}

// structMetaCache stores metadata for struct types.
var structMetaCache sync.Map // map[reflect.Type]*structMeta

// getStructMeta returns cached metadata for a struct type, creating it if needed.
func getStructMeta(structType reflect.Type) *structMeta {
	if meta, ok := structMetaCache.Load(structType); ok {
		return meta.(*structMeta)
	}

	meta := &structMeta{
		fields:  make(map[string]int),
		methods: make(map[string]int),
	}

	// Index fields. Fields of sync and sync/atomic types are left out, so a
	// script cannot lock, unlock, or copy a host's locks.
	for i := range structType.NumField() {
		field := structType.Field(i)
		if field.IsExported() && !isSyncType(field.Type) {
			meta.fields[field.Name] = i
		}
	}

	// Index methods on pointer type (includes both pointer and value receiver
	// methods), except those promoted from an embedded sync type
	ptrType := reflect.PointerTo(structType)
	for i := range ptrType.NumMethod() {
		method := ptrType.Method(i)
		if method.IsExported() && !promotedFromSync(structType, method.Name) {
			meta.methods[method.Name] = i
		}
	}

	structMetaCache.Store(structType, meta)
	return meta
}

// isSyncType reports whether t, or the type t points to, is from package sync
// or sync/atomic. Scripts never see values of these types: a script that
// locks a host mutex can hang the host, and unlocking an unlocked mutex is a
// fatal error that recover cannot catch.
func isSyncType(t reflect.Type) bool {
	t = derefType(t)
	return t.PkgPath() == "sync" || t.PkgPath() == "sync/atomic"
}

// promotedFromSync reports whether the method name of structType comes from
// an embedded sync or sync/atomic type. It follows Go's selector rule: the
// shallowest embedding depth that has the method wins, and a method declared
// on structType itself is at depth 0, so it shadows a promoted one.
func promotedFromSync(structType reflect.Type, name string) bool {
	if declaresMethod(structType, name) {
		return false
	}
	level := []reflect.Type{structType}
	seen := map[reflect.Type]bool{structType: true}
	for len(level) > 0 {
		var next []reflect.Type
		fromSync, fromOther := false, false
		for _, t := range level {
			for i := range t.NumField() {
				field := t.Field(i)
				if !field.Anonymous {
					continue
				}
				if isSyncType(field.Type) {
					if _, ok := reflect.PointerTo(derefType(field.Type)).MethodByName(name); ok {
						fromSync = true
					}
					continue
				}
				if declaresMethod(field.Type, name) {
					fromOther = true
				}
				if ft := derefType(field.Type); ft.Kind() == reflect.Struct && !seen[ft] {
					seen[ft] = true
					next = append(next, ft)
				}
			}
		}
		if fromSync || fromOther {
			return fromSync && !fromOther
		}
		level = next
	}
	return false
}

// declaresMethod reports whether t, or the type t points to, declares the
// method name itself, as opposed to promoting it from an embedded field. The
// Go toolchain marks the wrappers it generates for promoted methods with the
// file name "<autogenerated>".
func declaresMethod(t reflect.Type, name string) bool {
	t = derefType(t)
	for _, mt := range []reflect.Type{t, reflect.PointerTo(t)} {
		m, ok := mt.MethodByName(name)
		if !ok {
			continue
		}
		if !m.Func.IsValid() {
			// An interface method: promoted from an embedded interface
			// that is not a sync type
			return true
		}
		pc := m.Func.Pointer()
		if f := runtime.FuncForPC(pc); f != nil {
			if file, _ := f.FileLine(pc); file != "<autogenerated>" {
				return true
			}
		}
	}
	return false
}

func derefType(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	return t
}

// GoStruct wraps a Go struct for use in Risor.
// It exposes struct fields and methods via GetAttr/SetAttr.
type GoStruct struct {
	value      reflect.Value // The struct (always a pointer for addressability)
	structType reflect.Type  // The struct type (non-pointer)
	registry   *TypeRegistry // For type conversion
}

// NewGoStruct creates a new GoStruct wrapping the given Go struct pointer.
// The value must be a pointer to a struct.
func NewGoStruct(ptrVal reflect.Value, registry *TypeRegistry) *GoStruct {
	if ptrVal.Kind() != reflect.Ptr {
		panic(fmt.Sprintf("GoStruct: expected pointer, got %s", ptrVal.Kind()))
	}
	if ptrVal.Elem().Kind() != reflect.Struct {
		panic(fmt.Sprintf("GoStruct: expected pointer to struct, got pointer to %s", ptrVal.Elem().Kind()))
	}
	return &GoStruct{
		value:      ptrVal,
		structType: ptrVal.Elem().Type(),
		registry:   registry,
	}
}

func (g *GoStruct) Type() Type {
	return GOSTRUCT
}

func (g *GoStruct) Inspect() string {
	return fmt.Sprintf("go_struct(%s)", g.structType.String())
}

func (g *GoStruct) String() string {
	return g.Inspect()
}

func (g *GoStruct) Interface() any {
	return g.value.Interface()
}

func (g *GoStruct) Equals(other Object) bool {
	otherStruct, ok := other.(*GoStruct)
	if !ok {
		return false
	}
	// Compare by pointer identity. A struct field at offset 0 has the same
	// address as its enclosing struct, so the types must match too.
	return g.structType == otherStruct.structType &&
		g.value.Pointer() == otherStruct.value.Pointer()
}

func (g *GoStruct) Attrs() []AttrSpec {
	// Return specs for fields and methods
	meta := getStructMeta(g.structType)
	specs := make([]AttrSpec, 0, len(meta.fields)+len(meta.methods))

	for name := range meta.fields {
		specs = append(specs, AttrSpec{Name: name})
	}
	for name := range meta.methods {
		specs = append(specs, AttrSpec{Name: name})
	}

	return specs
}

func (g *GoStruct) GetAttr(name string) (Object, bool) {
	meta := getStructMeta(g.structType)

	// Check for field first
	if idx, ok := meta.fields[name]; ok {
		fieldVal := g.value.Elem().Field(idx)
		obj, err := g.registry.fromGoField(fieldVal)
		if err != nil {
			return nil, false
		}
		return obj, true
	}

	// Check for method
	if idx, ok := meta.methods[name]; ok {
		method := g.value.Method(idx)
		methodName := fmt.Sprintf("%s.%s", g.structType.Name(), name)
		fn := NewGoFunc(method, methodName, g.registry)
		fn.recv, fn.method = g.value, idx
		return fn, true
	}

	return nil, false
}

// SetAttr sets a field with the default limits. The VM calls SetAttrContext
// instead when the object is a *GoStruct.
func (g *GoStruct) SetAttr(name string, value Object) error {
	return g.SetAttrContext(context.Background(), name, value)
}

// SetAttrContext sets a field, converting value with the limits in ctx.
// The VM calls it only when the object's concrete type is exactly *GoStruct.
// For any other type, including one that embeds *GoStruct, the VM calls
// SetAttr: the type's own SetAttr if it defines one, or the promoted
// GoStruct.SetAttr if not. Both use the default limits, not the limits in
// ctx, which is the behavior before SetAttrContext existed.
func (g *GoStruct) SetAttrContext(ctx context.Context, name string, value Object) error {
	meta := getStructMeta(g.structType)

	idx, ok := meta.fields[name]
	if !ok {
		return TypeErrorf("go_struct %s has no field %q", g.structType.Name(), name)
	}

	fieldVal := g.value.Elem().Field(idx)
	if !fieldVal.CanSet() {
		return TypeErrorf("field %q of %s is not settable", name, g.structType.Name())
	}

	goVal, err := g.registry.ToGo(ctx, value, fieldVal.Type())
	if err != nil {
		return fmt.Errorf("cannot set field %q: %w", name, err)
	}
	rv, err := reflectValue(goVal, fieldVal.Type())
	if err != nil {
		return fmt.Errorf("cannot set field %q: %w", name, err)
	}
	fieldVal.Set(rv)
	return nil
}

func (g *GoStruct) IsTruthy() bool {
	return !g.value.IsNil()
}

func (g *GoStruct) RunOperation(opType op.BinaryOpType, right Object) (Object, error) {
	return nil, newTypeErrorf("unsupported operation for go_struct: %v", opType)
}

// Value returns the underlying Go struct pointer as a reflect.Value.
func (g *GoStruct) Value() reflect.Value {
	return g.value
}

// StructType returns the type of the underlying struct.
func (g *GoStruct) StructType() reflect.Type {
	return g.structType
}

// CallMethod calls a method on the struct by name with the given arguments.
// This is a convenience method that combines GetAttr and Call.
func (g *GoStruct) CallMethod(ctx context.Context, name string, args ...Object) (Object, error) {
	attr, ok := g.GetAttr(name)
	if !ok {
		return nil, fmt.Errorf("go_struct %s has no method %q", g.structType.Name(), name)
	}

	callable, ok := attr.(Callable)
	if !ok {
		return nil, fmt.Errorf("%q on %s is not callable", name, g.structType.Name())
	}

	return callable.Call(ctx, args...)
}
