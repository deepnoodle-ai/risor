// Command gen copies the specification's data files into Go source, so that
// the implementation builds its tables from them and never from text typed by
// hand. Run it from the module root with "GOWORK=off go generate ./...".
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen <input.json> <output.go> <package>")
		os.Exit(2)
	}
	in, out, pkg := os.Args[1], os.Args[2], os.Args[3]
	data, err := os.ReadFile(in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	src := fmt.Sprintf("// Code generated by internal/gen from suite/%s. DO NOT EDIT.\n\npackage %s\n\n// sourceJSON is the text of suite/%s.\nconst sourceJSON = %s\n",
		filepath.Base(in), pkg, filepath.Base(in), strconv.Quote(string(data)))
	if err := os.WriteFile(out, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
