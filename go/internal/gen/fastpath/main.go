// Command fastpath writes fastpath_gen.go: the adapters with no reflection
// that risor.Func and risor.Methods choose for the common shapes of Go
// function (bind.go states them). It runs from the module root by
// "go generate .".
//
// Each shape costs binary size in a host that calls Func or Methods, so
// the set is chosen, not every combination: about 1.4 KB for each shape of
// a function, and about 450 bytes for each shape of a method in each Go
// type given to Methods, since fastMethod is generic (measured with Go
// 1.26 on darwin/arm64).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// A param is a Go parameter type of a fast shape and the adapter's method
// that converts an argument to it; "" for any, which takes the value as it
// is.
type param struct {
	goType string
	conv   string
}

var params = []param{
	{"string", "argStr"},
	{"int", "argInt"},
	{"int64", "argInt64"},
	{"float64", "argFloat64"},
	{"bool", "argBool"},
	{"any", ""},
}

// box gives the expression that makes a result r of a Go type a value.
func box(goType, r string) string {
	switch goType {
	case "int":
		return "intResult(int64(" + r + "))"
	case "int64":
		return "intResult(" + r + ")"
	case "float64":
		return "floatResult(" + r + ")"
	}
	return r
}

// A result is the results of a fast shape: none, error, T or (T, error).
type result struct {
	goType string // T, or ""
	err    bool
}

func results() []result {
	out := []result{{}, {err: true}}
	for _, p := range params {
		out = append(out, result{goType: p.goType}, result{goType: p.goType, err: true})
	}
	return out
}

func (r result) text() string {
	switch {
	case r.goType == "" && !r.err:
		return ""
	case r.goType == "":
		return " error"
	case !r.err:
		return " " + r.goType
	}
	return " (" + r.goType + ", error)"
}

// A lead is a first parameter that is not an argument.
type lead struct{ goType, arg string }

var (
	noLead   = lead{}
	callLead = lead{"*Call", "c"}
	ctxLead  = lead{"context.Context", "c.Context()"}
)

// A shape is a lead, a list of parameter types and the results.
type shape struct {
	lead   lead
	params []param
	result result
}

// funcShapes are the fast shapes of a function: bind.go states them.
func funcShapes() []shape {
	var lists [][]param
	lists = append(lists, nil)
	for _, p := range params {
		lists = append(lists, []param{p})
	}
	for _, p := range params {
		lists = append(lists, []param{p, p})
	}
	for _, p := range params[1:] {
		lists = append(lists, []param{params[0], p})
	}
	for _, p := range params {
		lists = append(lists, []param{p, p, p})
	}
	var out []shape
	for _, l := range lists {
		for _, r := range results() {
			out = append(out, shape{noLead, l, r})
		}
	}
	for _, ld := range []lead{callLead, ctxLead} {
		for _, l := range lists[:1+len(params)] {
			for _, r := range results() {
				if r.err {
					out = append(out, shape{ld, l, r})
				}
			}
		}
	}
	return out
}

// methodShapes are the fast shapes of a method, after its receiver: the
// getters and the setters.
func methodShapes() []shape {
	var out []shape
	for _, r := range results() {
		out = append(out, shape{noLead, nil, r})
	}
	for _, p := range params {
		out = append(out, shape{noLead, []param{p}, result{}}, shape{noLead, []param{p}, result{err: true}})
	}
	return out
}

func main() {
	out := flag.String("o", "fastpath_gen.go", "the output file")
	flag.Parse()

	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("// Code generated by go run ./internal/gen/fastpath. DO NOT EDIT.\n\n")
	w("package risor\n\nimport \"context\"\n\n")

	write := func(method bool, shapes []shape) {
		off := 0
		if method {
			off = 1
		}
		for _, s := range shapes {
			var goParams, callArgs []string
			if method {
				goParams = append(goParams, "R")
				callArgs = append(callArgs, "r")
			}
			if s.lead.goType != "" {
				goParams = append(goParams, s.lead.goType)
				callArgs = append(callArgs, s.lead.arg)
			}
			for i, p := range s.params {
				goParams = append(goParams, p.goType)
				callArgs = append(callArgs, fmt.Sprintf("x%d", i))
			}
			r := s.result
			w("\tcase func(%s)%s:\n", strings.Join(goParams, ", "), r.text())
			w("\t\treturn func(c *Call, args []any) (any, error) {\n")
			if method {
				w("\t\t\tr, err := recv(a, args)\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n")
			}
			for i, p := range s.params {
				if p.conv == "" {
					w("\t\t\tx%d := args[%d]\n", i, i+off)
					continue
				}
				w("\t\t\tx%d, err := a.%s(args, %d)\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", i, p.conv, i+off)
			}
			call := "f(" + strings.Join(callArgs, ", ") + ")"
			switch {
			case r.goType == "" && !r.err:
				w("\t\t\t%s\n\t\t\treturn nil, nil\n", call)
			case r.goType == "":
				w("\t\t\treturn nil, %s\n", call)
			case !r.err:
				w("\t\t\treturn %s, nil\n", box(r.goType, call))
			default:
				w("\t\t\tv, err := %s\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n\t\t\treturn %s, nil\n", call, box(r.goType, "v"))
			}
			w("\t\t}\n")
		}
	}

	fs, ms := funcShapes(), methodShapes()
	w("// fastFunc gives the adapter of fn when its Go type is one of the %d fast\n// shapes of a function, else nil.\n", len(fs))
	w("func fastFunc(fn any, a *adapter) Native {\n\tswitch f := fn.(type) {\n")
	write(false, fs)
	w("\t}\n\treturn nil\n}\n\n")
	w("// fastMethod gives the adapter of fn, a method expression whose receiver\n// is R, when its Go type is one of the %d fast shapes of a method, else\n// nil. recv gives the receiver of a call.\n", len(ms))
	w("func fastMethod[R any](fn any, a *adapter, recv func(*adapter, []any) (R, error)) Native {\n\tswitch f := fn.(type) {\n")
	write(true, ms)
	w("\t}\n\treturn nil\n}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "fastpath: %d function shapes, %d method shapes\n", len(fs), len(ms))
}
