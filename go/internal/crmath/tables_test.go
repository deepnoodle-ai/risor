// TestTables recomputes the fast phase's tables with the big-number kernels
// and checks tables_data.go against them. To write the file:
//
//	RISOR_CRMATH_GEN=1 GOWORK=off go test -run TestTables ./internal/crmath
func TestTables(t *testing.T) {
	src := tablesSource(buildTables())
	if os.Getenv("RISOR_CRMATH_GEN") != "" {
		assert.Nil(t, os.WriteFile("tables_data.go", src, 0o644))
		return
	}
	have, err := os.ReadFile("tables_data.go")
	assert.Nil(t, err)
	assert.True(t, bytes.Equal(have, src), "tables_data.go differs from the computed tables")
}

const tabPrec = 256

func toDD(v *big.Float) [2]float64 {
	h, _ := v.Float64()
	r := new(big.Float).SetPrec(v.Prec()+64).Sub(v, new(big.Float).SetFloat64(h))
	l, _ := r.Float64()
	return [2]float64{h, l}
}

func ratDD(n, d int64) [2]float64 {
	return toDD(nf(tabPrec).Quo(ival(n, tabPrec), ival(d, tabPrec)))
}

func buildTables() *fastTables {
	const w = tabPrec
	t := new(fastTables)
	l2 := ln2C.get(w)
	t.ln2 = toDD(l2)
	for i := range 64 {
		a := nf(w).Mul(l2, ival(int64(i), w))
		t.exp64[i] = toDD(expBig(nf(w).Quo(a, ival(64, w)), w))
		t.exp4096[i] = toDD(expBig(nf(w).Quo(a, ival(4096, w)), w))
	}
	t.ln2by4096 = toDD(nf(w).Quo(l2, ival(4096, w)))
	t.c6 = ratDD(1, 6)

	for i := range t.logR {
		r := 1.0
		if i > 0 {
			// 1/mid as a double; any double near it would do, the
			// table holds the exact −log of the one chosen.
			mid := new(big.Float).SetPrec(w).SetInt64(int64(2*len(t.logR) + 2*i + 1))
			mid.Quo(mid, ival(int64(2*len(t.logR)), w))
			r, _ = nf(w).Quo(ival(1, w), mid).Float64()
		}
		t.logR[i] = r
		t.logRL[i] = toDD(nf(w).Neg(logBig(fl(r, w), w)))
	}
	for k := range t.l1p {
		n := int64(1)
		if k%2 == 1 {
			n = -1
		}
		t.l1p[k] = ratDD(n, int64(k+1))
	}
	t.ilog10 = toDD(nf(w).Quo(ival(1, w), l10C.get(w)))

	t.cos64[0] = [2]float64{1, 0} // sinCosBig's stopping rule needs r ≠ 0
	for j := 1; j < len(t.sin64); j++ {
		s, c := sinCosBig(nf(w).Quo(ival(int64(j), w), ival(64, w)), w)
		t.sin64[j], t.cos64[j] = toDD(s), toDD(c)
	}
	t.s120 = ratDD(1, 120)
	t.s6 = ratDD(-1, 6)
	t.c24 = ratDD(1, 24)

	p := pi(1500)
	t.halfPi = toDD(nf(1500).SetMantExp(p, -1))
	t.pi = toDD(p)
	top := nf(1500).Quo(ival(2, 1500), p)
	top.SetMantExp(top, 64*len(t.twoOverPi))
	bi, _ := top.Int(nil)
	mask := new(big.Int).SetUint64(math.MaxUint64)
	for k := range t.twoOverPi {
		sh := uint(64 * (len(t.twoOverPi) - 1 - k))
		t.twoOverPi[k] = new(big.Int).And(new(big.Int).Rsh(bi, sh), mask).Uint64()
	}

	for j := 1; j < len(t.atan64); j++ {
		t.atan64[j] = toDD(atanBig(nf(w).Quo(ival(int64(j), w), ival(64, w)), w))
	}
	t.a3 = ratDD(-1, 3)
	t.a5 = ratDD(1, 5)
	return t
}

func hexf(v float64) string { return strconv.FormatFloat(v, 'x', -1, 64) }

func tablesSource(t *fastTables) []byte {
	var b bytes.Buffer
	pr := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	pair := func(v [2]float64) string { return "{" + hexf(v[0]) + ", " + hexf(v[1]) + "}" }
	pairs := func(name string, vs [][2]float64) {
		pr("\t%s: [%d][2]float64{\n", name, len(vs))
		for _, v := range vs {
			pr("\t\t%s,\n", pair(v))
		}
		pr("\t},\n")
	}
	pr("// Code generated by TestTables in tables_test.go. DO NOT EDIT.\n\n")
	pr("package crmath\n\n")
	pr("var tabs = fastTables{\n")
	pairs("exp64", t.exp64[:])
	pairs("exp4096", t.exp4096[:])
	pr("\tln2by4096: [2]float64%s,\n", pair(t.ln2by4096))
	pr("\tc6: [2]float64%s,\n", pair(t.c6))
	pr("\tlogR: [%d]float64{\n", len(t.logR))
	for _, v := range t.logR {
		pr("\t\t%s,\n", hexf(v))
	}
	pr("\t},\n")
	pairs("logRL", t.logRL[:])
	pr("\tln2: [2]float64%s,\n", pair(t.ln2))
	pairs("l1p", t.l1p[:])
	pr("\tilog10: [2]float64%s,\n", pair(t.ilog10))
	pairs("sin64", t.sin64[:])
	pairs("cos64", t.cos64[:])
	pr("\ts120: [2]float64%s,\n", pair(t.s120))
	pr("\ts6: [2]float64%s,\n", pair(t.s6))
	pr("\tc24: [2]float64%s,\n", pair(t.c24))
	pr("\ttwoOverPi: [%d]uint64{\n", len(t.twoOverPi))
	for _, v := range t.twoOverPi {
		pr("\t\t%#016x,\n", v)
	}
	pr("\t},\n")
	pr("\thalfPi: [2]float64%s,\n", pair(t.halfPi))
	pr("\tpi: [2]float64%s,\n", pair(t.pi))
	pairs("atan64", t.atan64[:])
	pr("\ta3: [2]float64%s,\n", pair(t.a3))
	pr("\ta5: [2]float64%s,\n", pair(t.a5))
	pr("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return src
}
