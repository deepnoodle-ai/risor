/// x = mo · 2^e with mo odd, for a finite x > 0.
fn odd_split(x: f64) -> (u64, i64) {
    let b = x.to_bits();
    let ex = ((b >> 52) & 0x7ff) as i64;
    let frac = b & ((1 << 52) - 1);
    let (m, e) = if ex == 0 {
        (frac, -1074)
    } else {
        (frac | (1 << 52), ex - 1075)
    };
    let tz = m.trailing_zeros();
    (m >> tz, e + tz as i64)
}

/// The double nearest to m · 2^e, ties to even, subnormals included; an
/// infinity when it rounds to 2^1024 or more. m > 0.
fn round_u128(m: u128, e: i64) -> f64 {
    let bl = 128 - m.leading_zeros() as i64;
    let top = bl - 1 + e;
    if top >= 1024 {
        return f64::INFINITY;
    }
    // The exponent of the last place of the result.
    let q = (top - 52).max(-1074);
    let shift = q - e;
    let mant: u64 = if shift <= 0 {
        (m << -shift) as u64
    } else if shift > 128 {
        0
    } else {
        let kept = if shift == 128 { 0 } else { (m >> shift) as u64 };
        let half = (m >> (shift - 1)) & 1 == 1;
        let below = m & ((1u128 << (shift - 1)) - 1) != 0;
        kept + (half && (below || kept & 1 == 1)) as u64
    };
    // mant ≤ 2^53, so mant · 2^q is exact; 2^1024 overflows.
    scale_wide(mant as f64, q)
}

/// m^n, when it fits in 128 bits.
fn ipow(m: u64, n: u32) -> Option<u128> {
    let mut acc: u128 = 1;
    for _ in 0..n {
        acc = acc.checked_mul(m as u128)?;
    }
    Some(acc)
}

/// x^y for x > 0, y not zero.
///
/// First the cases whose value is cheap to know exactly: a power of two to
/// an integer exponent, an integer power up to 64 whose odd part fits in 128
/// bits, √x (`sqrt` is correctly rounded), and k/2 powers of an exact square.
/// Each is rounded once, exactly. Other exact values need no care: the test
/// decides a value that is a double, and declines a midpoint.
///
/// Otherwise z = y · log x as a double-double: log x within 2^-87
/// (`log_core`), the product within 2^-102, so |Δz| ≤ 2^-86.9 |z|. e^z is
/// then within 2^-91 (`exp_core`) and e^Δz − 1 ≤ 2^-86.8 |z| of itself. The
/// test uses 2^-82 + 2^-78 |z|, at least 2^8 times either part.
///
/// e^z overflows from z = 709.7827 and rounds to zero below z = −745.1332
/// (2^-1075); z.h beyond 709.8 or −745.2 is beyond them by far more than Δz.
fn pow_pos(x: f64, y: f64) -> Option<f64> {
    if x == 1.0 || y == 1.0 {
        return Some(x);
    }
    if y == 0.5 {
        return Some(x.sqrt());
    }
    let (mo, e) = odd_split(x);
    if mo == 1 {
        // x = 2^e: x^y = 2^(e y), exact when e y is an integer.
        let ey = e as f64 * y;
        if (e as f64).mul_add(y, -ey) == 0.0 && ey.fract() == 0.0 {
            return Some(if ey >= 1024.0 {
                f64::INFINITY
            } else if ey < -1076.0 {
                0.0
            } else {
                round_u128(1, ey as i64)
            });
        }
    } else if y.fract() == 0.0 && (2.0..=64.0).contains(&y) {
        if let Some(p) = ipow(mo, y as u32) {
            return Some(round_u128(p, e * y as i64));
        }
    } else if (2.0 * y).fract() == 0.0 && (1.5..=32.0).contains(&y) && x >= pow2(-900) {
        // y = k/2, k odd. When √x is exact, x^y = (√x)^k. Above 2^-900,
        // s² − x is a multiple of 2^-1006 or zero, so `mul_add` sees zero
        // only when it is.
        let s = x.sqrt();
        if s.mul_add(s, -x) == 0.0 {
            let (ms, es) = odd_split(s);
            let k = (2.0 * y) as u32;
            if let Some(p) = ipow(ms, k) {
                return Some(round_u128(p, es * k as i64));
            }
        }
    }
    let z = log_core(x).mul_d(y);
    if z.h > 709.8 {
        return Some(f64::INFINITY);
    }
    if z.h < -745.2 {
        return Some(0.0);
    }
    let (v, m) = exp_core(z);
    finish(v, m, pow2(-82) + z.h.abs() * pow2(-78))
}

/// x^y. The arguments pass the value test of `not_real`. The early returns
/// are those of the exact path (`math.rs`, pow).
pub(super) fn pow(x: f64, y: f64) -> Option<f64> {
    if y == 0.0 {
        return Some(1.0);
    }
    if x == 0.0 {
        return Some(0.0);
    }
    if !x.is_finite() || !y.is_finite() {
        return None;
    }
    let yi = y.fract() == 0.0;
    if x < 0.0 && !yi {
        return None;
    }
    let neg = x < 0.0 && super::is_odd(y);
    let v = pow_pos(x.abs(), y)?;
    Some(if neg { -v } else { v })
}

