//! The fast phase of the F13 math functions.
//!
//! Each function here evaluates its result in double-double arithmetic (a
//! value is an unevaluated sum hi + lo of two doubles) with a proven bound on
//! its relative error, then makes the rounding test of `decide`: when both
//! ends of the error interval round to the same double, that double is the
//! correctly rounded result. Otherwise, and for every argument a function
//! here does not take, it returns `None` and the exact path of `math.rs`
//! decides. Nearly every call ends here; the exact path stays the fallback
//! and, in the tests, the oracle.
//!
//! The tables are in `tables.rs`, generated by `gen.rs` from the exact
//! kernels. No platform function gives any digit of a result: the only
//! operations are +, −, ×, ÷, `sqrt` and `mul_add` of IEEE 754 (each correctly
//! rounded), conversions between integers and doubles, and exact scaling by
//! powers of two.
//!
//! # The error model
//!
//! u = 2^-53 is the unit roundoff. `two_sum`, `fast_two_sum` and `two_prod`
//! are exact (no result here comes near underflow where they are used, except
//! where a comment says that the term is negligible anyway). For the
//! double-double operations the bounds used are looser than those proved in
//! the literature (Joldes, Muller and Popescu, "Tight and rigorous error
//! bounds for basic building blocks of double-word arithmetic", 2017):
//!
//! | Operation | Bound used |
//! | --- | --- |
//! | `add`, `add_d` | 2^-103 · (\|a\| + \|b\|) |
//! | `mul`, `mul_d` | 2^-102 · \|a b\| |
//! | `div` | 2^-98 · \|a / b\| |
//! | `sqrt` | 2^-98 · \|√a\| |
//! | a table entry or constant | 2^-105 of its value |
//!
//! Each function states its own bound, built from these, and the bound its
//! rounding test uses, which is at least 2^8 times larger.

use super::tables as tb;

/// A double-double: the value h + l, with |l| at most about ulp(h).
#[derive(Clone, Copy, Debug)]
struct Dd {
    h: f64,
    l: f64,
}

const fn dd(b: [u64; 2]) -> Dd {
    Dd {
        h: f64::from_bits(b[0]),
        l: f64::from_bits(b[1]),
    }
}

const fn d(h: f64) -> Dd {
    Dd { h, l: 0.0 }
}

/// a + b exactly, as s + e.
#[inline(always)]
fn two_sum(a: f64, b: f64) -> Dd {
    let s = a + b;
    let bb = s - a;
    Dd {
        h: s,
        l: (a - (s - bb)) + (b - bb),
    }
}

/// a + b exactly, as s + e, when a is zero or |a| ≥ |b|.
#[inline(always)]
fn fast_two_sum(a: f64, b: f64) -> Dd {
    let s = a + b;
    Dd {
        h: s,
        l: b - (s - a),
    }
}

/// a · b exactly, as p + e: `mul_add` is a correctly rounded fused
/// multiply-add, so a · b − p is computed exactly.
#[inline(always)]
fn two_prod(a: f64, b: f64) -> Dd {
    let p = a * b;
    Dd {
        h: p,
        l: a.mul_add(b, -p),
    }
}

impl Dd {
    #[inline(always)]
    fn neg(self) -> Dd {
        Dd {
            h: -self.h,
            l: -self.l,
        }
    }

    #[inline(always)]
    fn add(self, o: Dd) -> Dd {
        let s = two_sum(self.h, o.h);
        fast_two_sum(s.h, s.l + (self.l + o.l))
    }

    #[inline(always)]
    fn add_d(self, b: f64) -> Dd {
        let s = two_sum(self.h, b);
        fast_two_sum(s.h, s.l + self.l)
    }

    #[inline(always)]
    fn mul(self, o: Dd) -> Dd {
        let p = two_prod(self.h, o.h);
        fast_two_sum(p.h, self.h.mul_add(o.l, self.l.mul_add(o.h, p.l)))
    }

    #[inline(always)]
    fn mul_d(self, b: f64) -> Dd {
        let p = two_prod(self.h, b);
        fast_two_sum(p.h, self.l.mul_add(b, p.l))
    }

    /// self / o. The remainder self.h − q1 · o.h of a correctly rounded
    /// quotient is a double, so the first two steps are exact.
    #[inline(always)]
    fn div(self, o: Dd) -> Dd {
        let q1 = self.h / o.h;
        let p = two_prod(q1, o.h);
        let r = (((self.h - p.h) - p.l) + self.l) - q1 * o.l;
        fast_two_sum(q1, r / o.h)
    }

    /// √self, for self > 0. As in `div`, h − s² is a double.
    #[inline(always)]
    fn sqrt(self) -> Dd {
        let s = self.h.sqrt();
        let p = two_prod(s, s);
        let r = ((self.h - p.h) - p.l) + self.l;
        fast_two_sum(s, r / (2.0 * s))
    }
}

/// 2^k, for k in the normal range.
const fn pow2(k: i64) -> f64 {
    f64::from_bits(((k + 1023) as u64) << 52)
}

/// v · 2^k, exact when the result is a normal double; an infinity when it
/// overflows. k is in [-1022, 2046].
fn scale(v: f64, k: i64) -> f64 {
    if k > 1023 {
        v * pow2(1023) * pow2(k - 1023)
    } else {
        v * pow2(k)
    }
}

/// The rounding test. v approximates the exact value y with
/// |y − v| ≤ ε0 |y|, and eps ≥ 4 ε0 (every caller has at least 2^8). Let
/// e = eps |h|. Then fl(l − e) ≤ l − ε0 |y| and fl(l + e) ≥ l + ε0 |y|: the
/// roundings of l ± e move them by at most u (|l| + e), and |l| ≤ 2^-52 |h|,
/// which eps − ε0 covers. Rounding to nearest is monotonic, so
/// RN(h + fl(l − e)) ≤ RN(y) ≤ RN(h + fl(l + e)); when the two ends are equal
/// they are RN(y). Each end is one correctly rounded addition, so this holds
/// in the subnormal range too; but below 2^-960 the roundings of l ± e
/// are no longer relative, and the test declines.
#[inline(always)]
fn decide(v: Dd, eps: f64) -> Option<f64> {
    let a = v.h.abs();
    if a.is_nan() || a < pow2(-960) || a == f64::INFINITY {
        return None;
    }
    let e = eps * a;
    let lo = v.h + (v.l - e);
    let hi = v.h + (v.l + e);
    (lo == hi).then_some(lo)
}

// ---- exp ---------------------------------------------------------------------

/// e^z = V · 2^m, for a double-double z with |z| ≤ 746.
///
/// Method. N = round(z · 4096 / ln 2) = 4096 m + 64 i + j with i, j in
/// [0, 64); r = z − N ln2/4096, |r| ≤ 2^-13.4 (the half step 2^-13.56, and the
/// roundings of z · 4096/ln 2 move N by at most 2^-29 of a step). Then
/// e^z = 2^m · 2^(i/64) · 2^(j/4096) · e^r.
///
/// The reduction. ln2/4096 = C1 + C2 + C3 to about 2^-170. N · C1 and N · C2
/// are exact (`two_prod`), z.h − N C1 is exact (`two_sum`). The small parts
/// (each below 2^-43: |N| < 2^22.1, |z| < 2^9.6) are summed in doubles with
/// four roundings of at most 2^-53 · 2^-41: |Δr| ≤ 2^-92.
///
/// e^r = 1 + r + r²/2 + r³ Q(r), Q = 1/6 + r/24 + r²/120 + r³/720 in doubles:
/// the terms left out are below 2^-91 / 5040 < 2^-103. r³ Q ≈ r³/6 ≤ 2^-42.8
/// is computed with a relative error of at most 8u = 2^-50 (the roundings of
/// r³ and of Horner, the coefficients, r.h in place of r): 2^-92.8. r + r²/2
/// and the sums are double-double: below 2^-101. With e^r's own change under
/// Δr: |Δ e^r| ≤ 2^-92.8 + 2^-92 + 2^-101 ≤ 2^-91.3 of e^r ≥ 0.9999.
///
/// The two table entries and two products add 2 · 2^-105 + 2 · 2^-102. The
/// bound on V: 2^-91 relative, for an exact z.
fn exp_core(z: Dd) -> (Dd, i64) {
    const K: f64 = 4096.0 / std::f64::consts::LN_2;
    let c = tb::LN2_4096.map(f64::from_bits);
    let nf = (z.h * K).round();
    let n = nf as i64;
    let p1 = two_prod(nf, c[0]);
    let s = two_sum(z.h, -p1.h);
    let p2 = two_prod(nf, c[1]);
    let small = ((s.l - p1.l) - p2.l) + (z.l - nf * c[2]);
    let r0 = two_sum(s.h, -p2.h);
    let r = two_sum(r0.h, r0.l + small);
    let rh = r.h;
    let q =
        (rh * rh * rh) * (1.0 / 6.0 + rh * (1.0 / 24.0 + rh * (1.0 / 120.0 + rh * (1.0 / 720.0))));
    let r2 = r.mul(r);
    let poly = d(1.0).add(
        r.add(Dd {
            h: r2.h * 0.5,
            l: r2.l * 0.5,
        })
        .add_d(q),
    );
    let tab = dd(tb::EXP_T1[((n >> 6) & 63) as usize]).mul(dd(tb::EXP_T2[(n & 63) as usize]));
    (tab.mul(poly), n >> 12)
}

/// The result V · 2^m, V from `exp_core` (so 0.9998 < V < 2), when the test
/// decides it, for a relative bound eps on V.
///
/// From m = −1021 on, V · 2^m ≥ 2^-1022 is normal: scaling the correctly
/// rounded V by 2^m is exact, and overflows exactly when the correctly
/// rounded result is 2^1024 or more.
///
/// Below, the result is on the grid of 2^-1074, which is fixed there: let
/// w = V · 2^(m+1074) < 2^53 (exact scaling), in units of 2^-1074; the result
/// is the integer nearest to w. With n = round(w.h), f = (w.h − n) + w.l
/// (w.h − n is exact, the sum within 2^-54) is w − n, moved by one to
/// [−1/2, 1/2] when w.h ends in one half (exactly, by Sterbenz); when
/// |f| + eps w.h < 1/2 − 2^-40, the exact value is within 1/2 of n, and n
/// units is the result (a double: n ≤ 2^53).
fn finish(v: Dd, m: i64, eps: f64) -> Option<f64> {
    if m >= -1021 {
        return Some(scale(decide(v, eps)?, m));
    }
    let k = m + 1074;
    let (wh, wl) = (scale_wide(v.h, k), scale_wide(v.l, k));
    let mut n = wh.round();
    let mut f = (wh - n) + wl;
    // round(w.h) may be the other neighbor of w when w.h ends in one half.
    if f.abs() > 0.5 {
        n += f.signum();
        f -= f.signum();
    }
    (f.abs() + eps * wh < 0.5 - pow2(-40)).then(|| scale_wide(n, -1074))
}

/// e^x. Bound 2^-91 (`exp_core`); the test uses 2^-82.
///
/// The early returns are those of the exact path (`math.rs`, exp): below
/// 2^-55, e^x is within 2|x| < 2^-54 of 1, less than half the gap to either
/// neighbor; beyond 710 and −746 it overflows or rounds to zero.
pub(super) fn exp(x: f64) -> Option<f64> {
    if x.abs() < pow2(-55) {
        return Some(1.0);
    }
    if x > 710.0 {
        return Some(f64::INFINITY);
    }
    if x < -746.0 {
        return Some(0.0);
    }
    if !x.is_finite() {
        return None;
    }
    let (v, m) = exp_core(d(x));
    finish(v, m, pow2(-82))
}

