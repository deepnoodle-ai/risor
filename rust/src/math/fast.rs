/// x = q π/2 + r for x ≥ 2^-27: (r, q mod 4), r a double-double with
/// |r| ≤ π/4 and a relative error of at most 2^-100; `None` when |r| is below
/// 2^-99, which no double comes near (the nearest double to a multiple of π/2
/// is 2^-61 from it).
///
/// Below π/4, r = x and q = 0. Otherwise, the reduction of Payne and Hanek:
/// x = M · 2^E, M an integer below 2^53. The bits of 2/π of weight 2^(2−E)
/// and above contribute to x · 2/π a multiple of 4, which changes neither
/// q mod 4 nor r: they are skipped. The next 256 bits W, from weight
/// 2^(1−E), give y = M W / 2^254 ≡ x · 2/π (mod 4), short by the bits after
/// them: less than 2^53 · 2^E · 2^-(E+254) = 2^-201. M W is taken modulo
/// 2^256: its top two bits are y mod 4 and the rest the fraction of y,
/// exactly. q is the nearest integer and f = y − q in [−1/2, 1/2], within
/// 2^-201. f is cut to 128 bits from its first (2^-127 of f) and split into
/// two doubles (the second rounded, 2^-105 of f). With |f| ≥ 2^-100, f is
/// within 2^-100.9 of itself, and r = f · π/2 adds 2^-102 + 2^-105.
fn reduce(x: f64) -> Option<(Dd, u32)> {
    if x < 0.785 {
        return Some((d(x), 0));
    }
    let bits = x.to_bits();
    let m = ((bits & ((1 << 52) - 1)) | (1 << 52)) as u128;
    let e = ((bits >> 52) & 0x7ff) as i64 - 1075;
    // Bit b of 2/π (weight 2^-b, b ≥ 1) is bit g = b + 63 of the table,
    // counted from the most significant bit of word 0. The window starts at
    // b = E − 1, g = E + 62: at least 9 for x ≥ 0.785, at most 1,033, so
    // that the last word read is word 20.
    let g = (e + 62) as usize;
    let (k, s) = (g / 64, g % 64);
    let w = |i: usize| {
        let a = tb::TWO_OVER_PI[k + i];
        let v = if s == 0 {
            a
        } else {
            (a << s) | (tb::TWO_OVER_PI[k + i + 1] >> (64 - s))
        };
        v as u128
    };
    // M W modulo 2^256, in limbs l0 (least significant) to l3.
    let (p0, p1, p2, p3) = (m * w(3), m * w(2), m * w(1), m * w(0));
    let l0 = p0 as u64;
    let c1 = (p0 >> 64) + (p1 as u64 as u128);
    let l1 = c1 as u64;
    let c2 = (c1 >> 64) + (p1 >> 64) + (p2 as u64 as u128);
    let l2 = c2 as u64;
    let l3 = ((c2 >> 64) as u64)
        .wrapping_add((p2 >> 64) as u64)
        .wrapping_add(p3 as u64);
    let mut q = (l3 >> 62) as u32;
    // The fraction times 2^256, as two halves.
    let fh = ((l3 as u128) << 66) | ((l2 as u128) << 2) | ((l1 >> 62) as u128);
    let fl = ((l1 as u128) << 66) | ((l0 as u128) << 2);
    // A fraction in [1/2, 1) is f − 1 with the next q: negate the 256 bits.
    let neg = fh >> 127 == 1;
    let (ah, al) = if neg {
        q = q.wrapping_add(1);
        let al = (!fl).wrapping_add(1);
        (!fh + (al == 0) as u128, al)
    } else {
        (fh, fl)
    };
    if ah < 1 << 28 {
        return None;
    }
    // The first 128 bits of |f|, from its leading one: |f| ≈ t · 2^(-128-lz).
    let lz = ah.leading_zeros();
    let t = if lz == 0 {
        ah
    } else {
        (ah << lz) | (al >> (128 - lz))
    };
    let top = t >> 75;
    let sc = -128 - lz as i64;
    let f = Dd {
        h: top as f64 * pow2(75 + sc),
        l: (t - (top << 75)) as f64 * pow2(sc),
    };
    let r = f.mul(dd(tb::PIO2));
    Some((if neg { r.neg() } else { r }, q & 3))
}

/// sin r and cos r, for a double-double r with |r| ≤ π/4 + 2^-40.
///
/// Method. j = round(128 |r|) ≤ 101, a = j/128, t = |r| − a with |t| ≤ 2^-8
/// (r.h − a is exact by Sterbenz, then `two_sum`). sin(a + t) = S cos t + C
/// sin t, cos(a + t) = C cos t − S sin t, with S, C from the table.
///
/// sin t = t + t u (−1/6 + u W), u = t², W = 1/120 − u/5040 + u²/362880 in
/// doubles; the terms left out are below t^11/11! < 2^-105 |t|. u.h W
/// (below 2^-22.9) has an error below 2^-75; −1/6 is a double-double; so
/// the bracket is within 2^-75 and t u times it within 2^-91 |t|. Bound:
/// 2^-90 of sin t.
///
/// cos t = 1 − u/2 + u² V, V = 1/24 − u/720 + u²/40320 in doubles; the terms
/// left out are below t^10/10! < 2^-101. u² V ≤ 2^-36.6 is within 5u of it:
/// 2^-87.3. Bound: 2^-87 absolute.
///
/// The combination. cos(a + t) ≥ cos(π/4 + 2^-8) > 0.69, and for j ≥ 1,
/// sin(a + t) ≥ S/2: each is within 2^-87 · 2 + 2^-90 + 2^-100 ≤ 2^-85.9 of
/// itself. For j = 0, sin r = sin t: 2^-90. Bound: 2^-85.9 for each.
fn sin_cos(r: Dd) -> (Dd, Dd) {
    let neg = r.h < 0.0;
    let a = if neg { r.neg() } else { r };
    let j = (a.h * 128.0).round();
    let t = two_sum(a.h - j / 128.0, a.l);
    let u = t.mul(t);
    let uh = u.h;
    let w = 1.0 / 120.0 + uh * (-1.0 / 5040.0 + uh * (1.0 / 362880.0));
    let b = dd(tb::SIXTH).neg().add_d(uh * w);
    let st = t.add(t.mul(u).mul(b));
    let v = 1.0 / 24.0 + uh * (-1.0 / 720.0 + uh * (1.0 / 40320.0));
    let ct = d(1.0)
        .add(Dd {
            h: -0.5 * u.h,
            l: -0.5 * u.l,
        })
        .add_d(uh * uh * v);
    let j = j as usize;
    let (sj, cj) = (dd(tb::SIN128[j]), dd(tb::COS128[j]));
    let s = sj.mul(ct).add(cj.mul(st));
    let c = cj.mul(ct).add(sj.mul(st).neg());
    (if neg { s.neg() } else { s }, c)
}

/// sin (0), cos (1) or tan (2) of x.
///
/// Bound. r is within 2^-100 of itself (`reduce`), which moves sin r and
/// cos r by at most that relatively (|r cot r| ≤ 1, |r tan r| ≤ 1 on
/// [−π/4, π/4]) and tan r by 1.6 times it. With `sin_cos` and the quotient:
/// sin and cos within 2^-85.8, tan within 2^-84.8. The test uses 2^-76.
///
/// The early returns are those of the exact path (`math.rs`, trig and tiny):
/// below 2^-27, sin x and tan x are within x³/3 of x and cos x within x²/2
/// of 1, less than half the gap to a neighbor (at least 2^-53 |x|).
pub(super) fn trig(x: f64, which: u8) -> Option<f64> {
    let ax = x.abs();
    if ax < pow2(-27) {
        return Some(if which == 1 { 1.0 } else { x });
    }
    if !ax.is_finite() {
        return None;
    }
    let (r, q) = reduce(ax)?;
    let (s, c) = sin_cos(r);
    let (sv, cv) = match q {
        0 => (s, c),
        1 => (c, s.neg()),
        2 => (s.neg(), c.neg()),
        _ => (c.neg(), s),
    };
    let v = match which {
        0 => sv,
        1 => cv,
        _ => sv.div(cv),
    };
    let v = if x < 0.0 && which != 1 { v.neg() } else { v };
    decide(v, pow2(-76))
}

