/// log(1 + z) for a double-double z with |z| < 2^-9.
///
/// P = z + z²(−1/2 + z(1/3 + z(−1/4 + z R))), R = 1/5 − z/6 + … + z⁶/11 in
/// doubles. The terms left out are below |z|^12 / 12 < 2^-99 |z|. R ≈ 1/5 is
/// within 4u · 1/5 = 2^-53.3; z.h · R (below 2^-11.3) adds a rounding of
/// 2^-64.3; −1/4 + z R is then exact (`fast_two_sum`). So −1/4 + z R is
/// within 2^-9 · 2^-53.3 + 2^-64.3 < 2^-62 of itself, and that error reaches
/// P times z^4: relative to z, |z|^3 · 2^-62 = 2^-89. The double-double
/// steps add below 2^-100. Bound: 2^-88.5 of |z|.
#[inline(always)]
fn log1p_small(z: Dd) -> Dd {
    let zh = z.h;
    let r = 0.2
        + zh * (-1.0 / 6.0
            + zh * (1.0 / 7.0
                + zh * (-0.125 + zh * (1.0 / 9.0 + zh * (-0.1 + zh * (1.0 / 11.0))))));
    let y = fast_two_sum(-0.25, zh * r);
    let j = dd(tb::THIRD).add(z.mul(y));
    let k = d(-0.5).add(z.mul(j));
    z.add(z.mul(z.mul(k)))
}

/// log x, for a finite x > 0, as a double-double.
///
/// Method. x = 2^e · m with m in [1, 2); i, the first 9 bits of m's
/// fraction, picks the interval [1 + i/512, 1 + (i+1)/512). From i = 256 on,
/// m is halved and e raised by one, so that m is in [3/4, 3/2). With the
/// table's r_i (20 bits, `gen.rs`), z = m r_i − 1 is exact as a double-double
/// (`two_prod`, then p − 1 by Sterbenz, then `two_sum`), and |z| < 2^-9.
/// log x = e ln 2 + L_i + log(1 + z), L_i = −log r_i. At i = 0 and i = 511,
/// r_i = 1 and L_i = 0.
///
/// Error. When e = 0 and L_i = 0 the result is log(1 + z) alone: 2^-88.5.
/// Otherwise |log x| ≥ 2^-10 (x is outside [1 − 2^-10, 1 + 2^-9]; and when
/// e ≠ 0, |e ln 2 + L_i| ≥ 0.69 − 0.41 ≥ 0.27 |e|). Then the errors are:
/// log(1 + z), 2^-88.5 · 2^-9 = 2^-97.5 absolute; L_i, 2^-105 · 0.41; e ln 2,
/// with e ln2.h exact and e · ln2.l rounded, 2^-96 absolute and 2^-104 of
/// e ln 2; the sums, 2^-103 of the terms, at most 4 times the result. In all,
/// 2^-87.5 relative. Bound: 2^-87.
fn log_core(x: f64) -> Dd {
    let mut bits = x.to_bits();
    let mut e = ((bits >> 52) & 0x7ff) as i64;
    if e == 0 {
        bits = (x * pow2(64)).to_bits();
        e = ((bits >> 52) & 0x7ff) as i64 - 64;
    }
    e -= 1023;
    let i = ((bits >> 43) & 511) as usize;
    let mut m = f64::from_bits((bits & ((1 << 52) - 1)) | (1023 << 52));
    if i >= 256 {
        m *= 0.5;
        e += 1;
    }
    let p = two_prod(m, f64::from_bits(tb::LOG_R[i]));
    let z = two_sum(p.h - 1.0, p.l);
    let lz = log1p_small(z);
    let ln2 = dd(tb::LN2);
    let ef = e as f64;
    let a = two_prod(ef, ln2.h);
    fast_two_sum(a.h, a.l + ef * ln2.l)
        .add(dd(tb::LOG_L[i]))
        .add(lz)
}

/// log x. Bound 2^-87 (`log_core`); the test uses 2^-78.
pub(super) fn log(x: f64) -> Option<f64> {
    if x == 1.0 {
        return Some(0.0);
    }
    if x.is_nan() || x <= 0.0 || x == f64::INFINITY {
        return None;
    }
    decide(log_core(x), pow2(-78))
}

/// log10 x = log x · (1/ln 10). Bound 2^-87 + 2^-102 + 2^-105; the test
/// uses 2^-78. The powers of ten that are doubles are exact results, which
/// the test decides like any other double.
pub(super) fn log10(x: f64) -> Option<f64> {
    if x == 1.0 {
        return Some(0.0);
    }
    if x.is_nan() || x <= 0.0 || x == f64::INFINITY {
        return None;
    }
    decide(log_core(x).mul(dd(tb::INV_LN10)), pow2(-78))
}

