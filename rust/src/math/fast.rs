/// atan(a / b) for double-doubles a, b > 0, each within 2^-97 of itself, the
/// larger in [2^-1, 2^1) and the smaller above 2^-902 (see `atan2` for the
/// one case where it may be smaller).
///
/// Method. With the smaller over the larger, u in (0, 1]. j = round(128 u),
/// c = j/128, v = (u − c) / (1 + u c), |v| ≤ 2^-8; atan u = atan c + atan v.
/// u.h − c is exact by Sterbenz.
///
/// atan v = v + v w (−1/3 + w R), w = v², R = 1/5 − w/7 + w²/9 − w³/11 in
/// doubles; the terms left out are below v^13/13 < 2^-99 |v|. R is within
/// 2^-54.3, w.h R adds a rounding of 2^-71.3; the bracket is within 2^-69.7
/// and its product with v w within 2^-85.7 of |v|.
///
/// Error. For j = 0, atan u = atan v: 2^-85.7. Otherwise atan u ≥ 2^-8 and
/// the error of atan v, 2^-85.7 · 2^-8 absolute, is 2^-85.7 of it. u is
/// within 2^-97 + 2^-97 + 2^-98 of itself, which moves atan u by at most as
/// much relatively (u / ((1 + u²) atan u) ≤ 1); v's own steps and the table
/// add 2^-100. Taking π/2 − θ (θ ≤ π/4) keeps the bound, as the result is
/// then at least π/4. Bound: 2^-85.5.
fn atan_core(a: Dd, b: Dd) -> Dd {
    let swap = a.h > b.h || (a.h == b.h && a.l > b.l);
    let u = if swap { b.div(a) } else { a.div(b) };
    let j = (u.h * 128.0).round();
    let c = j / 128.0;
    let num = two_sum(u.h - c, u.l);
    let den = d(1.0).add(u.mul_d(c));
    let v = num.div(den);
    let w = v.mul(v);
    let wh = w.h;
    let r = 0.2 + wh * (-1.0 / 7.0 + wh * (1.0 / 9.0 + wh * (-1.0 / 11.0)));
    let br = dd(tb::THIRD).neg().add_d(wh * r);
    let at = v.add(v.mul(w).mul(br));
    let theta = dd(tb::ATAN128[j as usize]).add(at);
    if swap {
        dd(tb::PIO2).add(theta.neg())
    } else {
        theta
    }
}

/// The exponent of a positive finite double: v in [2^k, 2^(k+1)).
fn exponent(v: f64) -> i64 {
    let b = v.to_bits();
    let e = ((b >> 52) & 0x7ff) as i64;
    if e == 0 {
        -1011 - b.leading_zeros() as i64
    } else {
        e - 1023
    }
}

/// v · 2^k, exact when neither it nor any step leaves the normal range or v
/// is subnormal and is scaled up.
fn scale_wide(mut v: f64, mut k: i64) -> f64 {
    while k > 1000 {
        v *= pow2(1000);
        k -= 1000;
    }
    while k < -1000 {
        v *= pow2(-1000);
        k += 1000;
    }
    v * pow2(k)
}

/// atan2(y, x). Bound 2^-85.5 (`atan_core`); π − θ (θ ≤ π/2) is at least
/// π/2 and keeps it. The test uses 2^-77.
///
/// The early returns are those of the exact path (`math.rs`, atan2): on an
/// axis the angle is 0, π or ±π/2.
///
/// Both arguments are scaled by the same power of two, the larger to [1, 2).
/// When |y| < |x|, x > 0 and |y/x| < 2^-900 the result is near |y/x|, maybe
/// subnormal, and the exact path decides. Otherwise the smaller is exact
/// after scaling when above 2^-902; when it is not, the result is
/// π/2 − θ or π − θ with θ < 2^-890 and an absolute error far below 2^-900,
/// which is nothing next to the bound of a result above 1.
pub(super) fn atan2(y: f64, x: f64) -> Option<f64> {
    use std::f64::consts::{FRAC_PI_2, PI};
    if y == 0.0 {
        return Some(if x < 0.0 { PI } else { 0.0 });
    }
    if x == 0.0 {
        return Some(y.signum() * FRAC_PI_2);
    }
    if !y.is_finite() || !x.is_finite() {
        return None;
    }
    let (ay, ax) = (y.abs(), x.abs());
    let (ey, ex) = (exponent(ay), exponent(ax));
    if x == 1.0 && ay < pow2(-27) {
        // atan y is within |y|³/3 of y, less than half the gap to a
        // neighbor of y (as for tan in `trig`).
        return Some(y);
    }
    if x > 0.0 && ey - ex < -900 {
        return None;
    }
    let k = -ey.max(ex);
    let th = atan_core(d(scale_wide(ay, k)), d(scale_wide(ax, k)));
    let th = if x < 0.0 {
        dd(tb::PI).add(th.neg())
    } else {
        th
    };
    decide(if y < 0.0 { th.neg() } else { th }, pow2(-77))
}

/// √(1 − x²) for x in (0, 1), within 2^-98 + 2^-102 of itself. Below 1/2,
/// 1 − x² from the exact x² (2^-105); from 1/2 on, (1 − x)(1 + x), with 1 − x
/// exact by Sterbenz (2^-102).
fn cos_of_sin(x: f64) -> Dd {
    let s = if x < 0.5 {
        let p = two_prod(x, x);
        let s = two_sum(1.0, -p.h);
        fast_two_sum(s.h, s.l - p.l)
    } else {
        two_sum(1.0, x).mul_d(1.0 - x)
    };
    s.sqrt()
}

/// asin x = atan(|x| / √(1 − x²)), signed. Bound 2^-85.5; the test uses
/// 2^-77.
///
/// The early returns are those of the exact path (`math.rs`, asin): below
/// 2^-27, asin x is within x³/6 of x.
pub(super) fn asin(x: f64) -> Option<f64> {
    let ax = x.abs();
    if ax < pow2(-27) {
        return Some(x);
    }
    if ax == 1.0 {
        return Some(x * std::f64::consts::FRAC_PI_2);
    }
    if ax.is_nan() || ax >= 1.0 {
        return None;
    }
    let th = atan_core(d(ax), cos_of_sin(ax));
    decide(if x < 0.0 { th.neg() } else { th }, pow2(-77))
}

/// acos x = atan(√(1 − x²) / |x|), and π minus that for x < 0. Bound
/// 2^-85.5; the test uses 2^-77. For |x| below 2^-900 the quotient may be
/// subnormal, but the result is π/2 − θ with an absolute error of θ far below
/// 2^-900, as in `atan2`.
///
/// The early returns are those of the exact path (`math.rs`, acos).
pub(super) fn acos(x: f64) -> Option<f64> {
    use std::f64::consts::{FRAC_PI_2, PI};
    if x == 1.0 {
        return Some(0.0);
    }
    if x == -1.0 {
        return Some(PI);
    }
    if x == 0.0 {
        return Some(FRAC_PI_2);
    }
    let ax = x.abs();
    if ax.is_nan() || ax >= 1.0 {
        return None;
    }
    let th = atan_core(cos_of_sin(ax), d(ax));
    decide(
        if x < 0.0 {
            dd(tb::PI).add(th.neg())
        } else {
            th
        },
        pow2(-77),
    )
}

