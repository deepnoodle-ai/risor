// Generate src/library/mathtables.ts: the tables and constants of the fast
// phase of package F13 (src/library/mathfast.ts), computed once by the exact
// BigInt kernels of src/library/mathcr.ts and stored as literals.
//
// Each double-double entry [hi, lo] is hi = the double nearest the value and
// lo = the double nearest the rest, so |value - hi - lo| <= 2^-106 |value|
// (to within the kernels' error, which is far below that at the scale used).
//
// Run with `node scripts/mathtables.ts`. A test fails when the file is stale.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { atanRatio, bitLength, expFixed, fixed, ln2, logFixed, pi, roundExact, sinCos } from "../src/library/mathcr.ts";

/** The scale of every table computation: the kernels' errors of a few units are 2^-290 or less. */
const S = 300;

/** A fixed-point value v * 2^-S as [hi, lo]. */
function dd(v: bigint, scale = S): [number, number] {
  const hi = roundExact(v, -scale);
  const lo = roundExact(v - fixed(hi, scale), -scale);
  return [hi, lo];
}

/** The fixed-point value of an Approx m * 2^e at scale S. */
function atScale(m: bigint, e: number): bigint {
  const k = e + S;
  return k >= 0 ? m << BigInt(k) : m >> BigInt(-k);
}

/** v * 2^-S split into doubles whose first has at most `first` significant bits. */
function split3(v: bigint, first: number): [number, number, number] {
  const len = bitLength(v);
  const drop = BigInt(len - first);
  const v1 = (v >> drop) << drop;
  const a = roundExact(v1, -S);
  const r1 = v - v1;
  const b = roundExact(r1, -S);
  const c = roundExact(r1 - fixed(b, S), -S);
  return [a, b, c];
}

/** v * 2^-S as two truncated parts of `bits` significant bits each and two rounded doubles. */
function split4(v: bigint, bits: number): [number, number, number, number] {
  const parts: number[] = [];
  let r = v;
  for (let i = 0; i < 2; i++) {
    const drop = BigInt(bitLength(r) - bits);
    const t = (r >> drop) << drop;
    parts.push(roundExact(t, -S));
    r -= t;
  }
  const c = roundExact(r, -S);
  parts.push(c, roundExact(r - fixed(c, S), -S));
  return parts as [number, number, number, number];
}

function rational(n: bigint, d: bigint): bigint {
  return (n << BigInt(S)) / d;
}

function list(name: string, doc: string, xs: number[], per = 4): string {
  const lines: string[] = [];
  for (let i = 0; i < xs.length; i += per) lines.push("  " + xs.slice(i, i + per).map((x) => String(x)).join(", ") + ",");
  return `/** ${doc} */\nexport const ${name}: readonly number[] = [\n${lines.join("\n")}\n];\n`;
}

function constant(name: string, doc: string, x: number): string {
  return `/** ${doc} */\nexport const ${name} = ${String(x)};\n`;
}

export function mathTables(): string {
  const out: string[] = [
    "// Generated by scripts/mathtables.ts from the exact kernels of mathcr.ts. Do not edit.\n" +
      "// Each pair [hi, lo] is a double-double: hi the double nearest the value, lo the double nearest the rest.\n",
  ];
  const L = ln2(S);

  // exp: 2^(i/64) and 2^(j/4096), i, j = 0..63.
  const t1: number[] = [];
  const t2: number[] = [];
  for (let i = 0; i < 64; i++) {
    const a = expFixed((L * BigInt(i)) / 64n, S, 2n);
    t1.push(...dd(atScale(a.m, a.e)));
    const b = expFixed((L * BigInt(i)) / 4096n, S, 2n);
    t2.push(...dd(atScale(b.m, b.e)));
  }
  out.push(list("EXP_T1", "2^(i/64) for i = 0..63, as [hi, lo] pairs.", t1));
  out.push(list("EXP_T2", "2^(j/4096) for j = 0..63, as [hi, lo] pairs.", t2));
  const [e1, e2, e3] = split3(L / 4096n, 30);
  out.push(constant("LN2_4096_1", "ln2 / 4096, its first 30 bits: a product with an integer below 2^23 is exact.", e1));
  out.push(constant("LN2_4096_2", "ln2 / 4096, the next part.", e2));
  out.push(constant("LN2_4096_3", "ln2 / 4096, the next part.", e3));

  // log: c_i = 1 / (1 + i/512), correctly rounded (one IEEE division), and -ln c_i.
  const c: number[] = [];
  const lt: number[] = [];
  for (let i = 0; i < 512; i++) {
    const ci = 1 / (1 + i / 512);
    c.push(ci);
    const v = i === 0 ? 0n : -logFixed(ci, S).v;
    lt.push(...dd(v));
  }
  out.push(list("LOG_C", "c_i = 1 / (1 + i/512) rounded to a double, i = 0..511.", c));
  out.push(list("LOG_T", "-ln(c_i) for the c_i of LOG_C, as [hi, lo] pairs.", lt));
  const [l1, l2, l3] = split3(L, 42);
  out.push(constant("LN2_1", "ln 2, its first 42 bits: a product with an integer below 2^11 is exact.", l1));
  out.push(constant("LN2_2", "ln 2, the next part.", l2));
  out.push(constant("LN2_3", "ln 2, the next part.", l3));
  const L10 = logFixed(10, S).v;
  const [i10h, i10l] = dd((1n << BigInt(2 * S)) / L10);
  out.push(constant("INV_LN10_H", "1 / ln 10, hi.", i10h));
  out.push(constant("INV_LN10_L", "1 / ln 10, lo.", i10l));

  // 2/pi in limbs of 24 bits: 2/pi = sum of P[i] * 2^(-24 (i + 1)).
  const LIMBS = 56;
  const SP = 24 * LIMBS + 128;
  const twoOverPi = (1n << BigInt(2 * SP + 1)) / pi(SP);
  // A second computation at a larger scale must give the same limbs.
  const SQ = SP + 64;
  const check = (1n << BigInt(2 * SQ + 1)) / pi(SQ);
  const limbs: number[] = [];
  for (let i = 0; i < LIMBS; i++) {
    const a = Number((twoOverPi >> BigInt(SP - 24 * (i + 1))) & 0xffffffn);
    const b = Number((check >> BigInt(SQ - 24 * (i + 1))) & 0xffffffn);
    if (a !== b) throw new Error("the limbs of 2/pi are not settled");
    limbs.push(a);
  }
  out.push(list("TWO_OVER_PI", `2/pi in ${LIMBS} limbs of 24 bits: 2/pi = sum of P[i] * 2^(-24 (i + 1)).`, limbs, 8));
  const P = pi(S);
  const [pio2h, pio2l] = dd(P >> 1n);
  out.push(constant("PIO2_H", "pi / 2, hi.", pio2h));
  out.push(constant("PIO2_L", "pi / 2, lo.", pio2l));
  const [c1, c2, c3, c4] = split4(P >> 1n, 33);
  out.push(constant("PIO2_1", "pi / 2, its first 33 bits: a product with an integer below 2^20 is exact.", c1));
  out.push(constant("PIO2_2", "pi / 2, the next 33 bits.", c2));
  out.push(constant("PIO2_3", "pi / 2, the next part.", c3));
  out.push(constant("PIO2_4", "pi / 2, the next part.", c4));
  const [pih, pil] = dd(P);
  out.push(constant("PI_H", "pi, hi.", pih));
  out.push(constant("PI_L", "pi, lo.", pil));

  // sin and cos of j/256, j = 0..201 (201/256 > pi/4).
  const sc: number[] = [];
  for (let j = 0; j <= 201; j++) {
    const r = sinCos(j / 256, S);
    if (r.quadrant !== 0) throw new Error("sin and cos table: a reduced argument");
    sc.push(...dd(r.s), ...dd(r.c));
  }
  out.push(list("SINCOS", "sin(j/256) and cos(j/256) for j = 0..201, as [sin hi, sin lo, cos hi, cos lo].", sc));

  // atan(j/256), j = 0..256.
  const at: number[] = [];
  for (let j = 0; j <= 256; j++) at.push(...dd(atanRatio(BigInt(j), 256n, S).v));
  out.push(list("ATAN", "atan(j/256) for j = 0..256, as [hi, lo] pairs.", at));

  // The coefficients that the polynomials hold as double-doubles.
  const [th, tl] = dd(rational(1n, 3n));
  out.push(constant("THIRD_H", "1/3, hi.", th));
  out.push(constant("THIRD_L", "1/3, lo.", tl));
  const [sh, sl] = dd(rational(1n, 6n));
  out.push(constant("SIXTH_H", "1/6, hi.", sh));
  out.push(constant("SIXTH_L", "1/6, lo.", sl));
  return out.join("\n");
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  const here = dirname(fileURLToPath(import.meta.url));
  writeFileSync(join(here, "..", "src", "library", "mathtables.ts"), mathTables());
}
